#!/usr/bin/env python3
"""sync_skills.py -- generate the Codex copies of the project's agent skills.

    python tools/sync_skills.py            write .agents/skills/ from .claude/skills/
    python tools/sync_skills.py --check    exit 1 if .agents/skills/ is out of date

WHY TWO FOLDERS. Claude Code loads project skills only from .claude/skills/, and
OpenAI Codex only from .agents/skills/; neither reads the other's folder. A
symlink would avoid the copy, but on Windows git checks a committed symlink out
as a one-line text file unless core.symlinks is enabled, so it would silently
break skills for anyone cloning there.

ONE SOURCE OF TRUTH. .claude/skills/ is the original: edit a skill there, then
run this script. tools/verify.py runs it with --check, so a forgotten sync fails
the fast suite instead of leaving Codex users with a stale checklist.

WHAT THE COPY CHANGES. The body is copied unchanged, so skill text must stay
tool-neutral (no $ARGUMENTS, no /name invocations). In the frontmatter, Claude
Code extension fields are dropped, leaving the fields of the Agent Skills spec
(https://agentskills.io/specification) that Codex expects. A skill marked
`disable-model-invocation: true` (it must only run when a person asks for it)
also gets agents/openai.yaml with `allow_implicit_invocation: false`, the Codex
equivalent.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC = REPO_ROOT / ".claude" / "skills"
DST = REPO_ROOT / ".agents" / "skills"

# Frontmatter fields defined by the Agent Skills spec; everything else is a
# Claude Code extension and is left out of the Codex copy.
SPEC_FIELDS = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MARKER = "# Generated from .claude/skills/{name}/SKILL.md by tools/sync_skills.py - edit that file, not this one."
OPENAI_YAML = (
    "# Generated by tools/sync_skills.py from disable-model-invocation in .claude/skills/{name}/SKILL.md.\n"
    "# Codex runs this skill only when a person asks for it ($" "{name} or /skills).\n"
    "policy:\n"
    "  allow_implicit_invocation: false\n"
)


def split_frontmatter(text: str, where: Path) -> tuple[list[str], str]:
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise SystemExit(f"{where}: SKILL.md must start with a '---' frontmatter block")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1:])
    raise SystemExit(f"{where}: frontmatter block is not closed with '---'")


def parse_fields(fm: list[str]) -> list[tuple[str, list[str]]]:
    """Top-level keys with their raw lines (a key line plus any indented continuation)."""
    fields: list[tuple[str, list[str]]] = []
    for line in fm:
        if line and not line[0].isspace() and not line.startswith("#") and ":" in line:
            fields.append((line.split(":", 1)[0].strip(), [line]))
        elif fields:
            fields[-1][1].append(line)
    return fields


def scalar(lines: list[str]) -> str:
    return lines[0].split(":", 1)[1].strip().strip("'\"")


def build(skill_dir: Path) -> dict[Path, str]:
    """Expected Codex files for one skill, keyed by path relative to DST."""
    src = skill_dir / "SKILL.md"
    text = src.read_text(encoding="utf-8").replace("\r\n", "\n")
    fm, body = split_frontmatter(text, src)
    fields = parse_fields(fm)
    values = {k: v for k, v in fields}

    name = scalar(values["name"]) if "name" in values else ""
    desc = scalar(values["description"]) if "description" in values else ""
    rel = src.relative_to(REPO_ROOT)
    if name != skill_dir.name:
        raise SystemExit(f"{rel}: name '{name}' must equal its folder name '{skill_dir.name}'")
    if not NAME_RE.match(name) or len(name) > 64:
        raise SystemExit(f"{rel}: name must be 1-64 lowercase letters, digits and single hyphens")
    if not 1 <= len(desc) <= 1024:
        raise SystemExit(f"{rel}: description must be 1-1024 characters (Agent Skills spec), is {len(desc)}")

    kept = [MARKER.format(name=name)]
    for key, lines in fields:
        if key in SPEC_FIELDS:
            kept.extend(lines)
    out = {Path(name) / "SKILL.md": "---\n" + "\n".join(kept) + "\n---\n" + body}
    if scalar(values.get("disable-model-invocation", ["x: false"])).lower() == "true":
        out[Path(name) / "agents" / "openai.yaml"] = OPENAI_YAML.format(name=name)
    return out


def expected() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for skill_dir in sorted(p for p in SRC.iterdir() if (p / "SKILL.md").is_file()):
        files.update(build(skill_dir))
        # Bundled files (scripts, reference docs) travel with the skill unchanged.
        for f in sorted(skill_dir.rglob("*")):
            if f.is_file() and f.name != "SKILL.md":
                files[Path(skill_dir.name) / f.relative_to(skill_dir)] = f.read_text(encoding="utf-8").replace("\r\n", "\n")
    return files


def actual() -> dict[Path, str]:
    if not DST.exists():
        return {}
    return {f.relative_to(DST): f.read_text(encoding="utf-8").replace("\r\n", "\n")
            for f in DST.rglob("*") if f.is_file()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report differences, change nothing")
    ns = ap.parse_args(argv if argv is not None else sys.argv[1:])

    want, have = expected(), actual()
    stale = sorted(p for p in want if have.get(p) != want[p])
    extra = sorted(p for p in have if p not in want)

    if ns.check:
        if not stale and not extra:
            print(f"OK: .agents/skills matches .claude/skills ({len(want)} files)")
            return 0
        for p in stale:
            print(f"out of date: .agents/skills/{p.as_posix()}")
        for p in extra:
            print(f"not in .claude/skills: .agents/skills/{p.as_posix()}")
        print("Run: python tools/sync_skills.py")
        return 1

    for p in stale:
        target = DST / p
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(want[p], encoding="utf-8", newline="\n")
        print(f"wrote   .agents/skills/{p.as_posix()}")
    for p in extra:
        (DST / p).unlink()
        print(f"removed .agents/skills/{p.as_posix()}")
    # Drop folders left empty by removed skills or files.
    if DST.exists():
        for d in sorted((d for d in DST.rglob("*") if d.is_dir()), key=lambda d: len(d.parts), reverse=True):
            if not any(d.iterdir()):
                shutil.rmtree(d)
    if not stale and not extra:
        print(f"already in sync ({len(want)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
