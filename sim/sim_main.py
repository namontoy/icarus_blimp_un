# ---------------------------------------------------------------------------
# The closed loop
# ---------------------------------------------------------------------------
class ClosedLoopSim:
    def __init__(self, xml_path: Path, course: int, envelope_diameter: Optional[float] = None,
                 altitude_source: str = "none", seed: int = 0,
                 dll_path: Optional[Path] = None, control_hz: float = CONTROL_HZ,
                 print_period_s: float = 2.0, verbose: bool = True):
        self.xml_path = Path(xml_path)
        self.course = course
        self.envelope_diameter = envelope_diameter
        if altitude_source not in ALTITUDE_SOURCES:
            raise ValueError(f"altitude_source must be one of {ALTITUDE_SOURCES}")
        self.altitude_source = altitude_source
        self.seed = seed
        self.control_hz = control_hz
        self.control_dt = 1.0 / control_hz
        self.print_period_s = print_period_s
        self.verbose = verbose

        self.model = mujoco.MjModel.from_xml_path(str(self.xml_path))
        self.data = mujoco.MjData(self.model)
        physics_dt = float(self.model.opt.timestep)
        self.substeps = max(1, round(self.control_dt / physics_dt))
        if abs(self.substeps * physics_dt - self.control_dt) > 1e-6:
            print(f"[sim_main] NOTE: control_dt={self.control_dt}s is not an exact multiple "
                  f"of the model's physics timestep {physics_dt}s; using {self.substeps} "
                  f"substeps/tick (effective control dt={self.substeps * physics_dt:.6f}s)")

        self.course_name, self.order = read_course_order(self.model)

        # -- geometry ids, resolved by NAME, never hardcoded indices ---------
        self.envelope_gid = self.model.geom("envelope").id
        self.vehicle_bid = self.model.body("vehicle").id
        self.balloon_gids = {n: self.model.geom(f"balloon_{n}_geom").id for n in range(1, 5)}
        self.act_ids = {name: self.model.actuator(name).id for name in ACTUATOR_NAMES}
        self.act_ctrlrange = {name: tuple(self.model.actuator_ctrlrange[aid])
                               for name, aid in self.act_ids.items()}
        self.gravity_world = np.array(self.model.opt.gravity, dtype=float)

        # -- the REAL control core ------------------------------------------
        self.ctl = ffi.BlimpController(dll_path)
        self.ctl.init()
        # Keep the C core's idea of the airframe in step with the scene: the
        # scene records its per-motor cap and heavy trim as custom text.
        p = self.ctl.get_params()
        motor_max_gf = read_custom_float(self.model, "motor_max_gf")
        trim_gf = read_custom_float(self.model, "trim_heavy_gf")
        if motor_max_gf is not None:
            p.motor_max_thrust_n = motor_max_gf * 9.80665e-3
        if trim_gf is not None:
            p.hover_thrust_n = trim_gf * 9.80665e-3
        ok = self.ctl.set_params(p)
        if self.verbose:
            print(f"[sim_main] params from scene: motor_max={motor_max_gf} gf, "
                  f"hover(trim)={trim_gf} gf, set_params accepted-as-given={ok}; "
                  f"altitude_source={altitude_source}")

        # -- deterministic per-run sensor noise/bias -------------------------
        self.rng = np.random.default_rng(seed)
        self.gyro_bias = self.rng.normal(0.0, GYRO_BIAS_SIGMA_RADS, size=3)
        self.accel_bias = self.rng.normal(0.0, ACCEL_BIAS_SIGMA_MS2, size=3)
        self.baro_bias = float(self.rng.normal(0.0, BARO_BIAS_SIGMA_M))

        mujoco.mj_forward(self.model, self.data)
        self._prev_lin_vel_world = self._body_velocity_world()[3:6].copy()

        self.t_us = 0
        self.sim_time_s = 0.0
        self.core_wp_index = 0          # last-known blimp_guidance_t.wp_index
        self.judge_ptr = 0              # index into self.order for next expected touch
        self.judge_loop = 0
        self.judge_loop_start_s: Optional[float] = None
        self._prev_contact = {n: False for n in range(1, 5)}
        self._last_print_s = -1e9

        self.camera_site_id = self.model.site("camera_site").id
        self.camera_dz = read_custom_float(self.model, "camera_dz")
        if self.camera_dz is None:
            self.camera_dz = -0.35
        self._hint_bias = 0.0
        self._hint_wp = -1
        self._contact_latch_until = {n: -1.0 for n in range(1, 5)}
        self._last_credited = -1
        self._last_credited_s = -1e9
        self.state_time_s: Dict[str, float] = {name: 0.0 for name in ffi.GUID_STATE_NAMES.values()}
        self.min_range_ever_m: Dict[int, float] = {n: math.inf for n in range(1, 5)}
        self.warnings: List[str] = []
        self.loops: List[LoopResult] = [LoopResult(loop_index=0)]

    # -- helpers ---------------------------------------------------------------
    def _body_velocity_world(self) -> np.ndarray:
        res = np.zeros(6)
        mujoco.mj_objectVelocity(self.model, self.data, mujoco.mjtObj.mjOBJ_BODY,
                                  self.vehicle_bid, res, 0)
        return res

    def _body_velocity_local(self) -> np.ndarray:
        res = np.zeros(6)
        mujoco.mj_objectVelocity(self.model, self.data, mujoco.mjtObj.mjOBJ_BODY,
                                  self.vehicle_bid, res, 1)
        return res

    def _rot_world_from_body(self) -> np.ndarray:
        return np.array(self.data.xmat[self.vehicle_bid]).reshape(3, 3)

    def _synth_imu(self) -> "ffi.BlimpImuSample":
        vel_local = self._body_velocity_local()
        gyro_true = vel_local[0:3]

        vel_world = self._body_velocity_world()
        lin_vel_world = vel_world[3:6]
        a_world = (lin_vel_world - self._prev_lin_vel_world) / self.control_dt
        self._prev_lin_vel_world = lin_vel_world.copy()
        # Specific force = true acceleration minus gravity (what a real
        # accelerometer reads: +g "up" at rest, ~0 in free fall). See module
        # docstring / task report for why this is computed by finite
        # differencing the body's own world velocity rather than trusting an
        # assumed MuJoCo acceleration-sensor gravity convention.
        specific_force_world = a_world - self.gravity_world
        r_wb = self._rot_world_from_body()
        accel_true_body = r_wb.T @ specific_force_world
        mag_true_body = r_wb.T @ WORLD_MAG_DIR

        gyro = gyro_true + self.gyro_bias + self.rng.normal(0.0, GYRO_NOISE_SIGMA_RADS, size=3)
        accel = accel_true_body + self.accel_bias + self.rng.normal(0.0, ACCEL_NOISE_SIGMA_MS2, size=3)
        mag = mag_true_body + self.rng.normal(0.0, MAG_NOISE_SIGMA, size=3)
        mag_norm = np.linalg.norm(mag)
        if mag_norm > 1e-9:
            mag = mag / mag_norm

        true_alt = float(self.data.xpos[self.vehicle_bid, 2])
        baro_alt = true_alt + self.baro_bias + float(self.rng.normal(0.0, BARO_NOISE_SIGMA_M))
        range_alt = true_alt + float(self.rng.normal(0.0, RANGE_ALT_NOISE_SIGMA_M))
        range_valid = (self.altitude_source in ("tof", "both")
                       and RANGE_ALT_MIN_M <= range_alt <= RANGE_ALT_MAX_M)
        mag_valid = bool(self.rng.random() > MAG_DROPOUT_PROB)
        baro_valid = (self.altitude_source in ("baro", "both")
                      and bool(self.rng.random() > BARO_DROPOUT_PROB))

        return ffi.make_imu_sample(
            t_us=self.t_us, gyro=tuple(gyro), accel=tuple(accel), mag=tuple(mag),
            baro_alt=baro_alt, range_alt=range_alt,
            gyro_valid=True, accel_valid=True, mag_valid=mag_valid,
            baro_valid=baro_valid, range_valid=range_valid,
        )

    def _balloon_view(self, balloon_number: int):
        """True range/bearing/elevation of a balloon from the camera, and
        whether it is inside the field of view (before dropouts)."""
        gid = self.balloon_gids[balloon_number]
        p_target_world = np.array(self.data.geom_xpos[gid])
        p_cam_world = np.array(self.data.site_xpos[self.camera_site_id])
        d_world = p_target_world - p_cam_world
        r_wb = self._rot_world_from_body()
        d_body = r_wb.T @ d_world
        rng = float(np.linalg.norm(d_world))
        bearing = math.atan2(float(d_body[1]), float(d_body[0]))
        horiz = math.hypot(float(d_body[0]), float(d_body[1]))
        elev = math.atan2(float(d_body[2]), horiz)
        in_fov = (abs(bearing) <= FOV_HALF_ANGLE_RAD
                  and abs(elev) <= FOV_VERT_HALF_ANGLE_RAD
                  and MIN_PERCEPTION_RANGE_M <= rng <= MAX_PERCEPTION_RANGE_M)
        return rng, bearing, elev, in_fov

    def _synth_alt_fix(self) -> Tuple[float, bool]:
        """Offboard altitude fix from the nearest balloon in view, using the
        same geometry blimp.c uses for the target (camera offset, estimator
        pitch) and the same perception noise."""
        if not ALT_FIX_ENABLED:
            return 0.0, False
        best = None
        for n in range(1, 5):
            rng, _bearing, elev, in_fov = self._balloon_view(n)
            if in_fov and (best is None or rng < best[0]):
                best = (rng, elev)
        if best is None or self.rng.random() < PERCEPTION_DROPOUT_PROB:
            return 0.0, False
        rng, elev = best
        rng_n = max(0.0, rng + float(self.rng.normal(0.0, max(RANGE_NOISE_FLOOR_M, RANGE_NOISE_FRAC * rng))))
        elev_n = elev + float(self.rng.normal(0.0, ELEV_NOISE_SIGMA_RAD))
        pitch_est = float(self.ctl.get_state().pitch)
        alt = 2.0 - (rng_n * math.sin(elev_n - pitch_est) + self.camera_dz)
        return alt, True

    def _synth_target(self, balloon_number: int) -> Tuple["ffi.BlimpTargetObs", float, float, float]:
        """Returns (obs, true_range_m, true_bearing_rad, true_elevation_rad)."""
        gid = self.balloon_gids[balloon_number]
        p_target_world = np.array(self.data.geom_xpos[gid])
        # Observed from the CAMERA on the gondola, not from the envelope
        # centre - guidance.c's vision altitude fallback assumes exactly
        # this offset (params.cam_dz_m).
        p_cam_world = np.array(self.data.site_xpos[self.camera_site_id])
        d_world = p_target_world - p_cam_world
        r_wb = self._rot_world_from_body()
        d_body = r_wb.T @ d_world
        true_range = float(np.linalg.norm(d_world))
        true_bearing = math.atan2(float(d_body[1]), float(d_body[0]))
        horiz = math.hypot(float(d_body[0]), float(d_body[1]))
        true_elev = math.atan2(float(d_body[2]), horiz)

        if true_range < self.min_range_ever_m[balloon_number]:
            self.min_range_ever_m[balloon_number] = true_range

        in_fov = (abs(true_bearing) <= FOV_HALF_ANGLE_RAD
                  and abs(true_elev) <= FOV_VERT_HALF_ANGLE_RAD
                  and MIN_PERCEPTION_RANGE_M <= true_range <= MAX_PERCEPTION_RANGE_M)
        dropout = self.rng.random() < PERCEPTION_DROPOUT_PROB
        visible = bool(in_fov and not dropout)

        bearing_sigma = BEARING_NOISE_SIGMA_RAD + BEARING_NOISE_PER_M * true_range
        bearing = true_bearing + float(self.rng.normal(0.0, bearing_sigma))
        elev = true_elev + float(self.rng.normal(0.0, ELEV_NOISE_SIGMA_RAD))
        range_sigma = max(RANGE_NOISE_FLOOR_M, RANGE_NOISE_FRAC * true_range)
        rng_reading = max(0.0, true_range + float(self.rng.normal(0.0, range_sigma)))
        confidence = float(np.clip(1.0 - CONFIDENCE_RANGE_DECAY * true_range, 0.15, 1.0)) if visible else 0.0

        # Search hint: absolute heading in the core's own yaw frame. The core
        # zeroes yaw at arm, so express the truth in that frame via the
        # estimator's current yaw plus the true bearing, then corrupt it.
        if self._hint_wp != self.core_wp_index:
            self._hint_wp = self.core_wp_index
            self._hint_bias = float(self.rng.normal(0.0, HINT_BIAS_SIGMA_RAD))
        est_yaw = float(self.ctl.get_state().yaw)
        hint = est_yaw + true_bearing + self._hint_bias + float(self.rng.normal(0.0, HINT_NOISE_SIGMA_RAD))
        alt_fix, alt_fix_valid = self._synth_alt_fix()
        obs = ffi.make_target_obs(t_us=self.t_us, bearing_rad=bearing, elevation_rad=elev,
                                   range_m=rng_reading, confidence=confidence, visible=visible,
                                   hint_yaw_rad=hint, hint_valid=True,
                                   alt_fix_m=alt_fix, alt_fix_valid=alt_fix_valid)
        return obs, true_range, true_bearing, true_elev

    def _contacts_this_tick(self) -> Dict[int, bool]:
        contact_now = {n: False for n in range(1, 5)}
        for i in range(int(self.data.ncon)):
            c = self.data.contact[i]
            g1, g2 = int(c.geom1), int(c.geom2)
            if g1 != self.envelope_gid and g2 != self.envelope_gid:
                continue
            other = g2 if g1 == self.envelope_gid else g1
            for n, gid in self.balloon_gids.items():
                if other == gid:
                    contact_now[n] = True
        return contact_now

    def _judge_tick(self, contact_now: Dict[int, bool], requested_loops: int) -> bool:
        """Edge-triggered, rule-literal (Rule 4/5) lap timing, independent of
        blimp_guidance_t's own bookkeeping. Returns True once `requested_loops`
        loops have been judged complete."""
        for n in range(1, 5):
            edge = contact_now[n] and not self._prev_contact[n]
            self._prev_contact[n] = contact_now[n]
            if not edge:
                continue
            expected = self.order[self.judge_ptr]
            if n == self._last_credited and self.sim_time_s - self._last_credited_s < JUDGE_RECONTACT_GRACE_S:
                continue   # still pressing on / bouncing off the balloon just scored
            if n != expected:
                self.warnings.append(
                    f"t={self.sim_time_s:.2f}s: touched balloon {n} while waypoint "
                    f"{expected} (order position {self.judge_ptr}) was expected — "
                    f"out-of-order touch, would VOID a real run under Rule 7; judge "
                    f"does not credit it"
                )
                continue
            loop = self.loops[self.judge_loop]
            if self.judge_ptr == 0:
                self.judge_loop_start_s = self.sim_time_s
                loop.start_time_s = self.sim_time_s
            prev_t = loop.touches[-1].sim_time_s if loop.touches else self.judge_loop_start_s
            leg_time = self.sim_time_s - prev_t if prev_t is not None else 0.0
            self._last_credited = n
            self._last_credited_s = self.sim_time_s
            loop.touches.append(WaypointTouch(
                loop_index=self.judge_loop, order_pos=self.judge_ptr,
                balloon_number=n, sim_time_s=self.sim_time_s, leg_time_s=leg_time,
            ))
            self.judge_ptr += 1
            if self.judge_ptr >= len(self.order):
                loop.completed = True
                loop.finish_time_s = self.sim_time_s
                loop.total_time_s = self.sim_time_s - loop.start_time_s
                self.judge_ptr = 0
                self.judge_loop += 1
                if self.judge_loop >= requested_loops:
                    return True
                self.loops.append(LoopResult(loop_index=self.judge_loop))
        return False

    def _apply_actuators(self, act: "ffi.BlimpActuators") -> None:
        for name, value in (("motor_fl", act.thrust_fl), ("motor_fr", act.thrust_fr),
                            ("motor_rl", act.thrust_rl), ("motor_rr", act.thrust_rr)):
            lo, hi = self.act_ctrlrange[name]
            self.data.ctrl[self.act_ids[name]] = float(np.clip(value, lo, hi))

    def _maybe_print(self, guid: "ffi.BlimpGuidance", act: "ffi.BlimpActuators",
                      true_range: float, true_bearing: float) -> None:
        if not self.verbose or self.sim_time_s - self._last_print_s < self.print_period_s:
            return
        self._last_print_s = self.sim_time_s
        p = self.data.xpos[self.vehicle_bid]
        st = self.ctl.get_state()
        state_name = ffi.GUID_STATE_NAMES.get(guid.state, f"?{guid.state}")
        target_n = self.order[self.core_wp_index % len(self.order)]
        print(f"  t={self.sim_time_s:6.2f}s  guid={state_name:9s} armed={self.ctl.get_armed()} "
              f"wp_idx={guid.wp_index} loop={guid.loop_index} target=balloon_{target_n} "
              f"pos=({p[0]:+.2f},{p[1]:+.2f},{p[2]:+.2f}) yaw={math.degrees(st.yaw):+6.1f}deg "
              f"range={true_range:5.2f}m bear={math.degrees(true_bearing):+6.1f}deg "
              f"est_alt={st.altitude:.2f}{'' if st.altitude_valid else '?'} vz={st.vz:+.2f} "
              f"alt_err={self.ctl.get_demand().fz:+.2f} "
              f"act=(FL{act.thrust_fl:.3f} FR{act.thrust_fr:.3f} RL{act.thrust_rl:.3f} "
              f"RR{act.thrust_rr:.3f}{' T' if act.clamped_total else ''}"
              f"{' Y' if act.clamped_yaw else ''}{' H' if act.clamped_heave else ''})")

    # -- the run -----------------------------------------------------------
    def run(self, max_sim_time_s: float, requested_loops: int) -> RunResult:
        result = RunResult(
            course=self.course, course_name=self.course_name, order=list(self.order),
            envelope_diameter=self.envelope_diameter, altitude_source=self.altitude_source,
            seed=self.seed, control_hz=self.control_hz, max_sim_time_s=max_sim_time_s,
            requested_loops=requested_loops,
        )
        if self.verbose:
            print(f"[sim_main] course={self.course} ({self.course_name}) order={self.order} "
                  f"loops_requested={requested_loops} max_sim_time={max_sim_time_s}s "
                  f"control_hz={self.control_hz} seed={self.seed} "
                  f"altitude_source={self.altitude_source}")
            print(f"[sim_main] core version: {self.ctl.version()!r}")

        finished = False
        while self.sim_time_s < max_sim_time_s:
            imu = self._synth_imu()
            target_balloon = self.order[self.core_wp_index % len(self.order)]
            obs, true_range, true_bearing, true_elev = self._synth_target(target_balloon)

            contact_now = self._contacts_this_tick()
            # guidance.h's CONFIRM dwells on contact_detected for touch_confirm_s,
            # so the core needs a LEVEL ("in contact right now"), not an edge.
            # The real touch detector must latch its output the same way.
            if contact_now[target_balloon]:
                self._contact_latch_until[target_balloon] = self.sim_time_s + CONTACT_LATCH_S
            core_contact_level = (contact_now[target_balloon]
                                  or self.sim_time_s < self._contact_latch_until[target_balloon])

            self.ctl.notify_link(self.t_us)
            inp = ffi.make_input(imu, obs, t_us=self.t_us, contact_detected=core_contact_level,
                                  arm_request=True)
            act = self.ctl.step(inp)

            guid = self.ctl.get_guidance()
            self.core_wp_index = guid.wp_index
            state_name = ffi.GUID_STATE_NAMES.get(guid.state, f"?{guid.state}")
            self.state_time_s[state_name] = self.state_time_s.get(state_name, 0.0) + self.control_dt

            self._maybe_print(guid, act, true_range, true_bearing)

            if self._judge_tick(contact_now, requested_loops):
                finished = True

            self._apply_actuators(act)
            for _ in range(self.substeps):
                mujoco.mj_step(self.model, self.data)

            self.t_us += round(self.control_dt * 1e6)
            self.sim_time_s += self.control_dt

            if not np.all(np.isfinite(self.data.qpos)) or not np.all(np.isfinite(self.data.qvel)):
                result.warnings.append(
                    f"NaN/Inf detected in MuJoCo qpos/qvel at t={self.sim_time_s:.3f}s — aborting run"
                )
                break
            if finished:
                break

        result.sim_time_reached_s = self.sim_time_s
        result.loops = self.loops
        result.state_time_s = dict(self.state_time_s)
        result.min_range_ever_m = {n: (v if math.isfinite(v) else -1.0)
                                    for n, v in self.min_range_ever_m.items()}
        result.warnings.extend(self.warnings)

        completed_times = [l.total_time_s for l in self.loops if l.completed]
        if completed_times:
            result.best_time_s = min(completed_times)
            result.completed = True

        guid = self.ctl.get_guidance()
        st = self.ctl.get_state()
        p = self.data.xpos[self.vehicle_bid]
        result.final_diagnostics = {
            "sim_time_s": self.sim_time_s,
            "guidance_state": ffi.GUID_STATE_NAMES.get(guid.state, f"?{guid.state}"),
            "wp_index": guid.wp_index,
            "loop_index": guid.loop_index,
            "armed": self.ctl.get_armed(),
            "position": [float(p[0]), float(p[1]), float(p[2])],
            "yaw_deg": math.degrees(st.yaw),
            "attitude_valid": bool(st.attitude_valid),
            "altitude_valid": bool(st.altitude_valid),
            "judge_progress": f"{self.judge_ptr}/{len(self.order)} waypoints touched in "
                               f"loop {self.judge_loop} of {requested_loops}",
        }
        return result


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def print_result(result: RunResult) -> None:
    print()
    print(f"=== course {result.course} ({result.course_name}) — order {result.order} ===")
    for loop in result.loops:
        if loop.completed:
            print(f"  loop {loop.loop_index}: COMPLETED in {loop.total_time_s:.2f}s "
                  f"(first touch to final touch, Rule 4)")
            prev = loop.start_time_s
            for touch in loop.touches:
                print(f"      waypoint order-pos {touch.order_pos} (balloon "
                      f"{touch.balloon_number}): touched at t={touch.sim_time_s:.2f}s "
                      f"(leg {touch.leg_time_s:.2f}s)")
                prev = touch.sim_time_s
        else:
            n_touched = len(loop.touches)
            print(f"  loop {loop.loop_index}: NOT completed "
                  f"({n_touched}/{len(result.order)} waypoints touched)")
            for touch in loop.touches:
                print(f"      waypoint order-pos {touch.order_pos} (balloon "
                      f"{touch.balloon_number}): touched at t={touch.sim_time_s:.2f}s "
                      f"(leg {touch.leg_time_s:.2f}s)")
    print()
    if result.best_time_s is not None:
        print(f"BEST completed loop time: {result.best_time_s:.2f}s "
              f"(of {sum(1 for l in result.loops if l.completed)} completed / "
              f"{result.requested_loops} requested)")
    else:
        print(f"NO loop completed within {result.max_sim_time_s:.1f}s of simulated time.")
    print()
    print("Time spent per guidance state:")
    for name, secs in sorted(result.state_time_s.items(), key=lambda kv: -kv[1]):
        if secs > 0:
            print(f"    {name:10s} {secs:7.2f}s")
    print()
    print("Closest approach ever made to each waypoint (diagnostic — shows whether")
    print("the vehicle moves toward waypoints even if it never touches them):")
    for n in sorted(result.min_range_ever_m):
        v = result.min_range_ever_m[n]
        print(f"    balloon {n}: {v:.2f} m" if v >= 0 else f"    balloon {n}: never observed")
    print()
    print("Final diagnostics:")
    for k, v in result.final_diagnostics.items():
        print(f"    {k}: {v}")
    if result.warnings:
        print()
        print(f"Warnings ({len(result.warnings)}):")
        for w in result.warnings[:20]:
            print(f"    - {w}")
        if len(result.warnings) > 20:
            print(f"    ... and {len(result.warnings) - 20} more")
    print()


