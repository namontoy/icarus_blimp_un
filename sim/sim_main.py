def build_argparser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--course", type=int, choices=[1, 2], default=1)
    ap.add_argument("--xml", type=str, default=None,
                     help="scene XML path (default: sim/scene/course{N}.xml, generated "
                          "on demand via sim/scene/build_scene.py if missing)")
    ap.add_argument("--envelope-diameter", type=float, default=None)
    ap.add_argument("--altitude-source", choices=list(ALTITUDE_SOURCES), default="none",
                     help="synthetic altitude sensor; the real PCB has none")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-time", type=float, default=90.0, help="sim seconds")
    ap.add_argument("--loops", type=int, default=1,
                     help="how many completed loops this harness waits for before "
                          "stopping (see docs/09 on the current internal-loop-count "
                          "limitation)")
    ap.add_argument("--dll", type=str, default=None, help="override build/libblimp.dll path")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--print-period", type=float, default=2.0)
    return ap


def main(argv: Optional[List[str]] = None) -> int:
    ns = build_argparser().parse_args(argv if argv is not None else sys.argv[1:])
    xml_path = Path(ns.xml) if ns.xml else resolve_scene_xml(ns.course, ns.envelope_diameter)
    try:
        sim = ClosedLoopSim(
            xml_path=xml_path, course=ns.course, envelope_diameter=ns.envelope_diameter,
            altitude_source=ns.altitude_source, seed=ns.seed,
            dll_path=Path(ns.dll) if ns.dll else None,
            print_period_s=ns.print_period, verbose=not ns.quiet,
        )
    except ffi.BlimpFFIError as e:
        print(f"FAIL: {e}")
        return 1

    result = sim.run(max_sim_time_s=ns.max_time, requested_loops=ns.loops)
    print_result(result)

    if result.warnings and any("NaN/Inf" in w for w in result.warnings):
        print("FAIL: simulation produced NaN/Inf — this is a real bug, not an untuned-gain issue.")
        return 1
    if not result.completed:
        print("FAIL: course not completed within the time budget.")
        return 1
    print("PASS: course completed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
