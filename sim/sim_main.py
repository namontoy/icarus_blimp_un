# ---------------------------------------------------------------------------
# Tunable sim-harness constants. NONE of these are control gains — they model
# the (synthetic) sensors and perception pipeline, not the vehicle. Real
# control gains live entirely in blimp_params_t, on the C side.
# ---------------------------------------------------------------------------
CONTROL_HZ = 100.0  # docs/07 sec 4.2: "100-250 Hz class" control tick rate
CONTROL_DT = 1.0 / CONTROL_HZ

# -- perception (camera-ish bearing/elevation/range to the target balloon) --
# 58 x 45 degrees: the widest OV2640 lens type the team owns (modules B and N,
# measured with tools/lens_test on 2026-10-22, docs/10). Until then the sim
# assumed 90 x 70, a field no lens in the batch comes close to.
FOV_HALF_ANGLE_RAD = math.radians(29.0)       # horizontal half-angle
FOV_VERT_HALF_ANGLE_RAD = math.radians(22.5)  # vertical half-angle
# The detector is planned to run on 240 x 180 frames. The sim has no pixels:
# it observes angles, so the image size enters only through the noise levels
# below. At 58 degrees over 240 columns one pixel is 4.2 mrad, a 0.55 m
# balloon spans about 130 / range_m pixels (22 px at 6 m), and the sigmas
# below are then ~5 px of centroid error at 0 m growing by ~2.4 px per metre
# of range, ~5 px vertically, and 8 % of range from the apparent diameter
# (+/-3.5 px at 3 m). Those are pessimistic for a clean red blob, which is
# the safe side until the real detector's error is measured.
IMAGE_WIDTH_PX = 240
IMAGE_HEIGHT_PX = 180
MAX_PERCEPTION_RANGE_M = 6.0                  # beyond this, "not visible"
MIN_PERCEPTION_RANGE_M = 0.05
PERCEPTION_DROPOUT_PROB = 0.02                # per-tick random vision glitch
BEARING_NOISE_SIGMA_RAD = 0.02                # ~5 px at 240 x 180 / 58 deg
BEARING_NOISE_PER_M = 0.01                    # extra sigma per metre of range
ELEV_NOISE_SIGMA_RAD = 0.02
RANGE_NOISE_FRAC = 0.08                       # "may be crude (apparent size)"
RANGE_NOISE_FLOOR_M = 0.03
CONFIDENCE_RANGE_DECAY = 0.06                  # confidence falls off with range

# -- IMU (gyro/accel/mag/baro/range) --
GYRO_NOISE_SIGMA_RADS = 0.01
GYRO_BIAS_SIGMA_RADS = 0.03      # sampled ONCE per run, per axis (turn-on bias)
ACCEL_NOISE_SIGMA_MS2 = 0.05
ACCEL_BIAS_SIGMA_MS2 = 0.05
MAG_NOISE_SIGMA = 0.03           # additive noise on the unit field vector
MAG_DROPOUT_PROB = 0.01
BARO_NOISE_SIGMA_M = 0.08
BARO_BIAS_SIGMA_M = 0.20         # docs/07 sec 5.1: real baro accuracy ~+/-0.25 m
BARO_DROPOUT_PROB = 0.005
RANGE_ALT_NOISE_SIGMA_M = 0.01
RANGE_ALT_MAX_M = 4.0            # docs/07 sec 5.1: ToF range-limited ~4 m
RANGE_ALT_MIN_M = 0.0

# Arbitrary but fixed "magnetic north" direction, mostly horizontal with a
# small dip (plausible near-equatorial inclination) — there is no real
# magnetic survey to match in simulation, so this is just a stable reference
# direction for the estimator's magnetometer fusion to work against.
_WORLD_MAG_DIR_RAW = np.array([1.0, 0.0, -0.15])
WORLD_MAG_DIR = _WORLD_MAG_DIR_RAW / np.linalg.norm(_WORLD_MAG_DIR_RAW)

ACTUATOR_NAMES = ("motor_fl", "motor_fr", "motor_rl", "motor_rr")

# Which altitude sensor the synthetic IMU pretends to have. The confirmed PCB
# has NONE (MPU-6050 only), so the default is "none" and altitude is held from
# the target balloon's elevation inside guidance.c. "baro"/"tof"/"both" exist
# to evaluate what adding a breakout on the I2C header would buy.
ALTITUDE_SOURCES = ("none", "baro", "tof", "both")

# Offboard search hint (blimp_target_obs_t.hint_yaw_rad): a real ground
# station would compute the expected heading to the next balloon from the
# fixed course geometry, the announced order, the last touched balloon's
# position and the vehicle's telemetry yaw. This stand-in takes the true
# heading and corrupts it with a per-leg bias plus per-tick noise, so the
# core only ever sees a "roughly right" hint, never ground truth.
HINT_BIAS_SIGMA_RAD = math.radians(10.0)
HINT_NOISE_SIGMA_RAD = math.radians(3.0)

# Touch detector hold time: a real detector (IMU deceleration spike and/or
# vision proximity) latches its output for a moment; the core's CONFIRM
# dwell (touch_confirm_s) then rides on that latch rather than needing the
# envelope to stay physically pressed against the balloon for the whole
# dwell. The judge (Rule 4 timing) still uses the RAW contact edge.
CONTACT_LATCH_S = 0.35

# A real judge does not void a run because the envelope is still resting on
# the balloon it just scored, so repeated contact edges with the LAST
# credited balloon inside this window are ignored (they were previously
# logged as out-of-order touches - 20 per run, all with the same balloon).
JUDGE_RECONTACT_GRACE_S = 6.0

# The offboard perception reports an altitude fix from the NEAREST balloon
# in the camera's field of view (all four sit at 2.0 m, Rule 22), with the
# same range/elevation noise as the target observation.
ALT_FIX_ENABLED = True


# ---------------------------------------------------------------------------
# Scene resolution — reuses sim/scene/build_scene.py, never reimplements it.
# ---------------------------------------------------------------------------
def default_scene_path(course: int) -> Path:
    return SCENE_DIR / f"course{course}.xml"


def resolve_scene_xml(course: int, envelope_diameter: Optional[float],
                       out_path: Optional[Path] = None, force: bool = False) -> Path:
    """Returns a path to a generated course XML, invoking the REAL
    sim/scene/build_scene.py (never reimplementing its geometry) whenever the
    caller asked for a non-default envelope size, the target file doesn't
    exist yet, or `force` is set. Otherwise reuses whatever is already on
    disk at the default path (matching the documented flow of running
    `python sim/scene/build_scene.py` once, then `python sim/run_course.py`
    against its output)."""
    default_diam = 0.78  # build_scene.py's SceneParams.envelope_diameter default
    target = out_path or default_scene_path(course)
    non_default = envelope_diameter is not None and abs(envelope_diameter - default_diam) > 1e-9
    if target.exists() and not non_default and not force:
        return target

    cmd = [sys.executable, str(BUILD_SCENE_PY), "--course", str(course), "--out", str(target)]
    if envelope_diameter is not None:
        cmd += ["--envelope-diameter", str(envelope_diameter)]
    print(f"[sim_main] generating scene: {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.stdout:
        print(result.stdout, end="")
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        raise RuntimeError(f"sim/scene/build_scene.py failed (exit {result.returncode})")
    return target


def read_custom_float(model: "mujoco.MjModel", name: str) -> Optional[float]:
    """Reads a <custom><text name=...> scalar the scene generator wrote."""
    tid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_TEXT, name)
    if tid < 0:
        return None
    adr, size = int(model.text_adr[tid]), int(model.text_size[tid])
    raw = bytes(model.text_data[adr:adr + size]).decode("ascii", "ignore").rstrip("\x00")
    try:
        return float(raw)
    except ValueError:
        return None


def read_course_order(model: "mujoco.MjModel") -> Tuple[str, List[int]]:
    """Parses the <custom><text name="waypoint_order" .../></custom> that
    build_scene.py embeds in the generated MJCF (see its build_xml()), rather
    than hardcoding the rectangle-perimeter/figure-eight visiting order here.
    This is exactly the "runtime-loaded, never hardcoded" order Rule 2
    requires (docs/07 sec 6.1's own framing) — sim_main.py reads it from the
    scene the same way real perception would read it from an announced
    course sheet, not from a constant baked into this file."""
    course_name = None
    order = None
    for i in range(model.ntext):
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_TEXT, i)
        start = int(model.text_adr[i])
        raw = bytes(model.text_data[start:start + int(model.text_size[i])])
        text = raw.split(b"\x00", 1)[0].decode("ascii")
        if name == "course_name":
            course_name = text
        elif name == "waypoint_order":
            order = [int(tok) for tok in text.split(",") if tok]
    if order is None:
        raise RuntimeError("scene is missing its 'waypoint_order' custom text — "
                            "was it really generated by sim/scene/build_scene.py?")
    return course_name or "", order


