"""sim_main.py — closed-loop MuJoCo simulation of the REAL C control core.

THE POINT (see core/include/blimp/blimp.h, sim/blimp_ffi.py): this file drives
the exact compiled bytes that also run on the ESP32 — blimp_step(), via
ctypes, through build/libblimp.dll — around the actual competition course
generated by sim/scene/build_scene.py. It contains NO control, estimation, or
guidance logic of its own. Its only two jobs are:

  1. SYNTHESISE realistic sensor data from MuJoCo's ground truth (IMU with
     noise + bias, a target observation with noise + dropouts + a limited
     field of view) — never hand the estimator/guidance ground truth, or this
     stops being a real test of them.
  2. APPLY the C core's actuator output to MuJoCo's actuators, step physics,
     and detect real contact with the balloon geoms for the touch detector.

Everything about HOW the vehicle chooses to fly is entirely up to whatever is
compiled into build/libblimp.dll. If it flies badly, that is data about the
control core, not a bug in this file to "fix" by adding compensation here.

Timing (Rule 4/5): this file keeps its OWN independent, ground-truth judge of
lap time — the instant MuJoCo detects a NEW envelope/balloon contact in the
announced order — rather than trusting blimp_guidance_t's internal
bookkeeping alone (a real judge does not read firmware state; they watch the
airship touch balloons). Both are reported so the two can be cross-checked.

Usage (standalone, single run):
    python sim_main.py --course 1 --xml sim/scene/course1.xml
See run_course.py for the multi-loop CLI with a summary table.
"""
